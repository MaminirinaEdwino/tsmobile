package com.example.app.entity;

import java.util.List;

public class Sqlgenerator {

    public String generateDBAndTableInit(List<Model> models, String projectName) {
        StringBuilder sb = new StringBuilder();
        sb.append("-- SQL Schema for PostgreSQL\n");
        sb.append("-- Generated by TurboStack Java\n\n");

        if (models != null) {
            for (Model model : models) {
                String tableName = model.getNom().toLowerCase();
                sb.append(String.format("CREATE TABLE IF NOT EXISTS %s (\n", tableName));

                List<String> columns = new java.util.ArrayList<>();
                for (Champs field : model.getAttributs()) {
                    String fName = field.getNom().toLowerCase();
                    String fType = field.getType().toLowerCase();

                    boolean isSerial = false;
                    List<Object> constraints = field.getConstraint();
                    if (constraints != null) {
                        for (Object c : constraints) {
                            if (c != null && c.toString().toLowerCase().equals("primary key")) {
                                // Détection basique
                            }
                        }
                    }

                    String pgType = "TEXT";
                    if (fType.equals("int")) {
                        pgType = isSerial ? "SERIAL" : "INTEGER";
                    } else if (fType.equals("string")) {
                        pgType = "VARCHAR(255)";
                    }

                    StringBuilder colDef = new StringBuilder(String.format("\t%s %s", fName, pgType));

                    if (constraints != null) {
                        for (Object c : constraints) {
                            if (c == null) continue;
                            String cStr = c.toString().toLowerCase();
                            if (cStr.equals("primary key")) {
                                colDef.append(" PRIMARY KEY");
                            } else if (cStr.equals("unique")) {
                                colDef.append(" UNIQUE");
                            } else if (cStr.equals("not null")) {
                                colDef.append(" NOT NULL");
                            }
                        }
                    }
                    columns.add(colDef.toString());
                }
                sb.append(String.join(",\n", columns));
                sb.append("\n);\n\n");
            }
        }
        return sb.toString();
    }
}